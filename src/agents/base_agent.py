"""
Base agent abstraction for all agent types.
"""
import json
from abc import ABC, abstractmethod
from typing import Dict, List, Optional

from src.agents.conversation_history import ConversationHistory
from src.utils.logger import setup_experiment_logger, ExperimentLogger


class BaseAgent(ABC):
    """
    Abstract base class for all agents.

    Defines the core interface that all agents must implement,
    without imposing specific implementation details.
    """

    def __init__(
        self,
        role: str,
        system_prompt: str = "",
        logger: Optional[ExperimentLogger] = None,
    ) -> None:
        """
        Initialize base agent.

        Args:
            role: The role of the agent (e.g., "Tutor", "Student", "Judge").
            system_prompt: Initial system prompt to set the context.
            logger: ExperimentLogger instance. If None, a default one is created.
        """
        self.role = role
        self.system_prompt = system_prompt

        # Create or use provided experiment logger
        if logger is None:
            logger = setup_experiment_logger()

        # Get logger for this specific agent role
        self.logger = logger.get_logger(role.lower())

        # Initialize conversation history
        self.conversation = ConversationHistory(system_prompt=system_prompt)

    @property
    def messages_history(self) -> List[Dict[str, str]]:
        """
        Get conversation history.

        Returns:
            List of message dictionaries in the conversation history.
        """
        return self.conversation.get_messages()

    def _preprocess_input(self, user_input: str) -> str:
        """
        Preprocess incoming user input before adding to history.

        Subclasses can override this to implement role-specific
        input processing (e.g., JSON parsing).

        Args:
            user_input: Raw input from the other agent.

        Returns:
            Processed input string.
        """
        return user_input

    def _postprocess_output(self, agent_output: str) -> str:
        """
        Postprocess agent output before returning to caller.

        Subclasses can override this to implement role-specific
        output processing (e.g., JSON formatting).

        Args:
            agent_output: Raw output generated by the agent.

        Returns:
            Processed output string.
        """
        return agent_output

    @abstractmethod
    def _reply(self, user_input: str, **kwargs) -> str:
        """
        Generate a reply to the user input.

        Must be implemented by subclasses to define agent-specific behavior.

        Args:
            user_input: Processed user input.
            **kwargs: Additional generation parameters.

        Returns:
            Agent's response string.
        """
        raise NotImplementedError("_reply method must be implemented in subclasses.")

    def reply(self, user_input: str, **kwargs) -> str:
        """
        Generate a reply based on user input and conversation history.

        This method:
        1. Preprocesses the incoming message.
        2. Updates conversation history.
        3. Calls `_reply()` to generate a response.
        4. Logs the updated conversation state.

        Args:
            user_input: Latest message received from the other agent.
            with_history: Whether to include conversation history in the reply.
            **kwargs: Additional keyword arguments for generation.

        Returns:
            The agent's generated reply.
        """
        # Step 1. Preprocess input (subclass can override)
        user_input = self._preprocess_input(user_input)

        # Step 2. Add the other agent's message to history
        self.conversation.add_user_message(user_input)

        # Step 3. Call the internal _reply() to generate a response
        agent_output = self._reply(user_input, **kwargs)

        agent_output = self._postprocess_output(agent_output)

        # Step 4. Add the agent's response to history
        self.conversation.add_assistant_message(agent_output)

        # Step 5. Log the updated conversation state
        self.logger.info(
            f"[{self.role}] messages_history:\n{json.dumps(self.messages_history, indent=2, ensure_ascii=False)}"
        )

        return agent_output

    def reply_first(self, user_input: str, **kwargs) -> str:
        """
        Generate the first reply by adding user input as a system message.

        This method is typically used for the initial interaction where
        the user input should be added as a system message instead of a user message.

        This method:
        1. Preprocesses the incoming message.
        2. Adds the message as a system message to conversation history.
        3. Calls `_reply()` to generate a response.
        4. Logs the updated conversation state.

        Args:
            user_input: Initial message to add as system context.
            **kwargs: Additional keyword arguments for generation.

        Returns:
            The agent's generated reply.
        """
        # Step 1. Preprocess input (subclass can override)
        user_input = self._preprocess_input(user_input)

        # Step 2. Add the message as a system message to history
        self.conversation.add_message("system", user_input)

        # Step 3. Call the internal _reply() to generate a response
        agent_output = self._reply(user_input, **kwargs)

        # Step 4. Postprocess output
        agent_output = self._postprocess_output(agent_output)

        # Step 5. Add the agent's response to history
        self.conversation.add_assistant_message(agent_output)

        # Step 6. Log the updated conversation state
        self.logger.info(
            f"[{self.role}] messages_history:\n{json.dumps(self.messages_history, indent=2, ensure_ascii=False)}"
        )

        return agent_output